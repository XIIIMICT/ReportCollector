-- «Продуктовые позиции»: the product x ДЗО matrix (kppk_org_products).
--
-- This is the ONE input the source dumps never carried: the original copies
-- have products and ДЗО as separate dictionaries, and which product an asset
-- actually offers exists only in «Матрица продуктов.xlsx». It is kept here as
-- a plain table so the seeder needs no spreadsheet: names are matched exactly
-- (normalized: trimmed, single spaces) against kppk_orgs / kppk_products.
--
-- `has_excise` is «Заполняемый акциз»: a product x ДЗО pair that carries an
-- excise. It is business input, not source data — keep edits here when the
-- matrix changes.

CREATE TABLE kppk_product_matrix (
    org_name text NOT NULL,
    product_name text NOT NULL,
    has_excise boolean NOT NULL DEFAULT false,
    PRIMARY KEY (org_name, product_name)
);

